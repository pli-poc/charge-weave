import { test } from 'node:test';
import { strict as assert } from 'node:assert';
import { execFile, execFileSync } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { WorkspaceStore } from '../src/workspace.js';
import { importSourceManifest, sha256 } from '../src/source-manifest.js';
import { summarizeGeneratedArtifacts } from '../src/artifact-summary.js';
import { createPublicationCommit, preparePublicationCandidate } from '../src/publication-candidate.js';
import { pushPublication } from '../src/publication-push.js';

test('accepted source and generated bytes are staged only in a disposable checkout', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'chargeweave-stage-test-'));
  const repository = join(directory, 'repo'), current = fileURLToPath(new URL('../..', import.meta.url));
  const git = args => execFileSync('git', args, { cwd: repository, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  let store;
  try {
    mkdirSync(repository); mkdirSync(join(repository, 'model')); mkdirSync(join(repository, 'tools')); mkdirSync(join(repository, 'docs'));
    for (const path of ['authoring_adapter.py', 'domain_schema.py']) writeFileSync(join(repository, 'tools', path), readFileSync(join(current, 'tools', path)));
    const schema = 'MODULE|foundation\nRecord|root|A record.|\n';
    writeFileSync(join(repository, 'model', 'domain.schema'), schema);
    writeFileSync(join(repository, 'docs', 'generated.txt'), 'before\n');
    git(['init']); git(['add', '.']); git(['-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '-m', 'baseline']);
    const remote = join(directory, 'remote.git');
    execFileSync('git', ['init', '--bare', remote], { cwd: directory, stdio: 'ignore' });
    git(['remote', 'add', 'origin', remote]); git(['push', 'origin', 'HEAD:refs/heads/main']);
    const commit = git(['rev-parse', 'HEAD']);
    const database = join(directory, 'workspace.sqlite');
    store = new WorkspaceStore(database);
    const workspace = store.create({ title: 'Stage test', baselineCommit: commit, schema, sourceManifest: importSourceManifest(repository, commit) });
    store.apply({ workspaceId: workspace.id, actor: 'draft', operationId: 'edit', expectedRevision: 0, commands: [{ type: 'class.add', name: 'Candidate', module: 'foundation', parent: 'Record', definition: 'A review candidate.' }] });
    const candidate = store.get(workspace.id);
    const artifact = value => [{ path: 'docs/generated.txt', sha256: sha256(Buffer.from(value)), bytes: Buffer.byteLength(value) }];
    for (const profile of ['structural', 'reference', 'audit', 'acceptance']) {
      const job = store.createJob(workspace.id, 1, candidate.sourceDigest, 'validator', profile, profile).job;
      if (profile === 'acceptance') {
        store.saveJobArtifacts(job.id, summarizeGeneratedArtifacts(artifact('before\n'), artifact('after\n')));
        store.saveJobGeneratedFiles(job.id, [{ ...artifact('after\n')[0], content: Buffer.from('after\n') }]);
      }
      store.updateJob(job.id, 'passed');
    }
    const review = store.recordReview(workspace.id, { actor: 'reviewer', operationId: 'accept', expectedRevision: 1, sourceDigest: candidate.sourceDigest, decision: 'accept', reason: 'Reviewed the candidate and evidence.' });
    const capture = async path => artifact(readFileSync(join(path, 'docs', 'generated.txt'), 'utf8'));
    const build = async path => writeFile(join(path, 'docs', 'generated.txt'), 'after\n');
    const preview = await preparePublicationCandidate(store, workspace.id, review.id, repository, 'python', { capture, build });
    assert.deepEqual(preview.files.map(item => item.path), ['docs/generated.txt', 'model/domain.schema']);
    assert.equal(preview.files[0].sha256, sha256(Buffer.from('after\n')));
    assert.equal(git(['status', '--short']), '');
    assert.equal(readFileSync(join(repository, 'docs', 'generated.txt'), 'utf8'), 'before\n');
    const acceptance = review.evidence.find(item => item.profile === 'acceptance');
    store.db.prepare('UPDATE job_generated_files SET content = ? WHERE job = ?').run(Buffer.from('tampered\n'), acceptance.jobId);
    await assert.rejects(() => preparePublicationCandidate(store, workspace.id, review.id, repository, 'python', { capture, build }), /unavailable or incomplete|corrupt/);
    store.db.prepare('UPDATE job_generated_files SET content = ? WHERE job = ?').run(Buffer.from('after\n'), acceptance.jobId);
    const previewJob = store.createJob(workspace.id, 1, candidate.sourceDigest, 'reviewer', 'preview-job', 'publication-preview', review.id).job;
    store.saveJobArtifacts(previewJob.id, preview); store.updateJob(previewJob.id, 'passed');
    const intent = { actor: 'reviewer', operationId: 'reserve', expectedRevision: 1, sourceDigest: candidate.sourceDigest, reviewId: review.id, previewJobId: previewJob.id, subject: 'Add a candidate concept', body: 'Problem, change and validation evidence.' };
    const reservation = store.reservePublication(workspace.id, intent);
    assert.equal(reservation.state, 'prepared');
    assert.match(reservation.branch, /^chargeweave\/studio-/);
    assert.equal(store.reservePublication(workspace.id, intent).id, reservation.id);
    assert.throws(() => store.reservePublication(workspace.id, { ...intent, body: 'Different body' }), /reused/);
    const committed = await createPublicationCommit(store, workspace.id, reservation.id, repository, 'python', { capture, build, identity: { name: 'Test Reviewer', email: 'test@example.invalid' } });
    const commitSha = committed.commitSha;
    assert.match(commitSha, /^[a-f0-9]{40}$/);
    const bundle = store.publicationBundle(workspace.id, reservation.id);
    const bundlePath = join(directory, 'candidate.bundle');
    writeFileSync(bundlePath, bundle.content);
    git(['bundle', 'verify', bundlePath]);
    git(['fetch', '--no-tags', bundlePath, 'HEAD']);
    assert.equal(git(['rev-parse', `${commitSha}^`]), commit);
    await assert.rejects(() => createPublicationCommit(store, workspace.id, reservation.id, repository, 'python', { capture, build, identity: { name: 'Test Reviewer', email: 'test@example.invalid' } }), /not current and prepared/);
    const fixture = { remote, branch: 'main' };
    const execute = promisify(execFile);
    await assert.rejects(() => pushPublication(store, workspace.id, reservation.id, repository, null, fixture, { push: async (args, options) => {
      assert.throws(() => store.apply({ workspaceId: workspace.id, actor: 'draft', operationId: 'during-push', expectedRevision: 1, commands: [{ type: 'class.describe', name: 'Candidate', definition: 'Edit during push.' }] }), /push is in progress/);
      await execute('git', args, options); throw new Error('Simulated lost push response');
    } }), /Push outcome is unknown/);
    assert.equal(store.publication(workspace.id, reservation.id).state, 'push_unknown');
    assert.equal(git(['ls-remote', '--heads', 'origin', `refs/heads/${reservation.branch}`]).split(/\s+/)[0], commitSha);
    assert.equal(git(['ls-remote', '--heads', 'origin', 'refs/heads/main']).split(/\s+/)[0], commit);
    store.close(); store = new WorkspaceStore(database);
    assert.equal(store.publication(workspace.id, reservation.id).state, 'push_unknown');
    assert.equal(store.publication(workspace.id, reservation.id).commitSha, commitSha);
    assert.equal(store.publicationBundle(workspace.id, reservation.id).sha256, bundle.sha256);
    assert.deepEqual(store.publicationHistory(workspace.id).map(item => item.id), [reservation.id]);
    assert.throws(() => store.advancePublication(workspace.id, reservation.id, 'push_unknown', 'failed'), /Invalid publication transition/);
    assert.throws(() => store.advancePublication(workspace.id, reservation.id, 'push_unknown', 'pushed', 'c'.repeat(40)), /cannot change/);
    assert.equal((await pushPublication(store, workspace.id, reservation.id, repository, null, fixture)).publication.state, 'pushed');
    const second = store.reservePublication(workspace.id, { ...intent, operationId: 'reserve-second' });
    await createPublicationCommit(store, workspace.id, second.id, repository, 'python', { capture, build, identity: { name: 'Test Reviewer', email: 'test@example.invalid' } });
    await assert.rejects(() => pushPublication(store, workspace.id, second.id, repository, null, fixture, { push: async () => { throw new Error('Simulated connection loss before push'); } }), /Push outcome is unknown/);
    assert.equal(git(['ls-remote', '--heads', 'origin', `refs/heads/${second.branch}`]), '');
    assert.equal((await pushPublication(store, workspace.id, second.id, repository, null, fixture)).publication.state, 'pushed');
    const third = store.reservePublication(workspace.id, { ...intent, operationId: 'reserve-third' });
    await createPublicationCommit(store, workspace.id, third.id, repository, 'python', { capture, build, identity: { name: 'Test Reviewer', email: 'test@example.invalid' } });
    writeFileSync(join(repository, 'README.md'), 'remote advanced\n');
    git(['add', 'README.md']); git(['-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '-m', 'advance base']);
    git(['push', 'origin', 'HEAD:refs/heads/main']);
    await assert.rejects(() => pushPublication(store, workspace.id, third.id, repository, null, fixture), /Target branch changed/);
    assert.equal(store.publication(workspace.id, third.id).state, 'commit_created');
    assert.equal(git(['ls-remote', '--heads', 'origin', `refs/heads/${third.branch}`]), '');
    await assert.rejects(() => preparePublicationCandidate(store, workspace.id, review.id, repository, 'python', { capture, build: async path => writeFile(join(path, 'docs', 'generated.txt'), 'different\n') }), /differs from accepted evidence/);
    await assert.rejects(() => preparePublicationCandidate(store, workspace.id, review.id, repository, 'python', { capture, build: async path => writeFile(join(path, 'model', 'domain.schema'), 'rewritten\n') }), /Source differs from accepted manifest/);
    store.apply({ workspaceId: workspace.id, actor: 'draft', operationId: 'later', expectedRevision: 1, commands: [{ type: 'class.describe', name: 'Candidate', definition: 'Changed after review.' }] });
    await assert.rejects(() => preparePublicationCandidate(store, workspace.id, review.id, repository, 'python', { capture, build }), /Current accepted review/);
  } finally { store?.close(); rmSync(directory, { recursive: true, force: true }); }
});
