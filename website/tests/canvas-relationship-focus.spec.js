import { test, expect } from '@playwright/test';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { WorkspaceStore } from '../../ontology-authoring/src/workspace.js';
import { createHttpService } from '../../ontology-authoring/src/http.js';

test('inspected relationship can be emphasized without changing the model or layout', async ({ page, isMobile }) => {
  test.skip(isMobile, 'This checks the desktop relationship diagram.');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const store = new WorkspaceStore(':memory:');
  const workspace = store.create({ title: 'Relationship focus', baselineCommit: 'a'.repeat(40), schema: 'MODULE|foundation\nRecord|root|A record.|\nDevice|Record|A device.|peer:Record? owner:Record?\n' });
  const pairingCode = 'synthetic-pairing-code-'.repeat(2);
  const service = createHttpService({ store, token: 'test-token-'.repeat(4), pairingCode, workspaceId: workspace.id, staticDirectory: fileURLToPath(new URL('../dist/', import.meta.url)) });
  service.listen(0, '127.0.0.1'); await once(service, 'listening');
  try {
    await page.goto(`http://127.0.0.1:${service.address().port}/charge-weave-app/modelling/`);
    await page.getByLabel('Pairing code').fill(pairingCode);
    await page.getByRole('button', { name: 'Pair local studio' }).click();
    await page.getByLabel('Search model').fill('Device');
    await page.getByRole('button', { name: 'Search', exact: true }).click();
    await page.getByRole('button', { name: 'Device', exact: true }).click();
    const canvas = page.getByRole('region', { name: 'Relationships for Device' });
    await expect(canvas).toHaveAttribute('data-layout', 'ready');
    const positions = await page.evaluate(id => sessionStorage.getItem(`chargeweave.canvas.v2.${id}.default`), workspace.id);
    const picker = page.getByLabel('Inspect relationship');
    await picker.selectOption({ label: 'Device — peer → Record' });
    const details = page.getByRole('region', { name: 'Relationship details' });
    const toggle = details.getByRole('button', { name: 'Dim other relationships' });
    await expect(toggle).toHaveAttribute('aria-pressed', 'false');
    const peer = canvas.locator('.react-flow__edge').filter({ hasText: 'peer' });
    const owner = canvas.locator('.react-flow__edge').filter({ hasText: 'owner' });
    await toggle.focus(); await page.keyboard.press('Enter');
    await expect(toggle).toHaveAttribute('aria-pressed', 'true');
    await expect(peer).not.toHaveClass(/studio-flow-edge-muted/);
    await expect(owner).toHaveClass(/studio-flow-edge-muted/);
    await expect(owner).toHaveCSS('opacity', '0.18');
    await picker.selectOption({ label: 'Device — owner → Record' });
    await expect(owner).not.toHaveClass(/studio-flow-edge-muted/);
    await expect(peer).toHaveClass(/studio-flow-edge-muted/);
    await peer.focus();
    await expect(peer).toHaveCSS('opacity', '1');
    await toggle.focus();
    await expect(peer).toHaveCSS('opacity', '0.18');
    await page.emulateMedia({ forcedColors: 'active', reducedMotion: 'reduce' });
    await expect(peer).toHaveCSS('opacity', '0.55');
    await peer.focus();
    await expect(peer).toHaveCSS('opacity', '1');
    await page.emulateMedia({ forcedColors: 'none', reducedMotion: 'reduce' });
    await details.getByRole('button', { name: 'Close relationship details' }).click();
    await expect(canvas.locator('.studio-flow-edge-muted')).toHaveCount(0);
    await picker.selectOption({ label: 'Device — peer → Record' });
    await expect(toggle).toHaveAttribute('aria-pressed', 'false');
    expect(await page.evaluate(id => sessionStorage.getItem(`chargeweave.canvas.v2.${id}.default`), workspace.id)).toBe(positions);
    expect(store.get(workspace.id).revision).toBe(0);
  } finally { await page.close(); await service.shutdown(); store.close(); }
});
