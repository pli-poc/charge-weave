import { test, expect } from '@playwright/test';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { WorkspaceStore } from '../../ontology-authoring/src/workspace.js';
import { createHttpService } from '../../ontology-authoring/src/http.js';

test('open-view picker exposes and switches among views beyond the tab strip', async ({ page, isMobile }) => {
  const store = new WorkspaceStore(':memory:');
  const workspace = store.create({ title: 'View picker', baselineCommit: 'a'.repeat(40), schema: 'MODULE|foundation\nRecord|root|A record.|\nDevice|Record|A device.|\n' });
  const pairingCode = 'synthetic-pairing-code-'.repeat(2);
  const service = createHttpService({ store, token: 'test-token-'.repeat(4), pairingCode, workspaceId: workspace.id, staticDirectory: fileURLToPath(new URL('../dist/', import.meta.url)) });
  service.listen(0, '127.0.0.1'); await once(service, 'listening');
  try {
    await page.goto(`http://127.0.0.1:${service.address().port}/charge-weave-app/modelling/`);
    await page.getByLabel('Pairing code').fill(pairingCode);
    await page.getByRole('button', { name: 'Pair local studio' }).click();
    await page.getByLabel('Search model').fill('Device');
    await page.getByRole('button', { name: 'Search', exact: true }).click();
    await page.getByRole('button', { name: 'Device', exact: true }).click();
    if (isMobile) await page.getByRole('navigation', { name: 'Workspace sections' }).getByRole('button', { name: 'Diagram' }).click();
    for (const id of ['alpha', 'beta', 'gamma', 'a-long-view-name-that-does-not-fit']) {
      await page.getByLabel('View ID').fill(id);
      await page.getByRole('button', { name: 'Choose view ID' }).click();
      await expect(page.getByRole('navigation', { name: 'Open diagram views' }).getByRole('button', { name: id, exact: true })).toHaveAttribute('aria-current', 'page');
    }
    const picker = page.locator('.studio-view-picker');
    await picker.locator('summary').click();
    await expect(picker.getByRole('button', { name: 'a-long-view-name-that-does-not-fit', exact: true })).toBeVisible();
    const longEntry = picker.getByRole('button', { name: 'a-long-view-name-that-does-not-fit', exact: true });
    expect(await longEntry.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    await expect(picker.getByRole('button', { name: 'gamma', exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
    await picker.getByRole('button', { name: 'beta', exact: true }).click();
    await expect(picker).not.toHaveAttribute('open', '');
    await expect(page.getByRole('navigation', { name: 'Open diagram views' }).getByRole('button', { name: 'beta', exact: true })).toHaveAttribute('aria-current', 'page');
    await expect(picker.locator('summary')).toContainText('Views (5)');
    await picker.locator('summary').click();
    await picker.getByRole('button', { name: 'gamma', exact: true }).click();
    await page.getByLabel('Filter graph relationships').fill('no matching predicate');
    await picker.locator('summary').click();
    await expect(picker.getByRole('button', { name: 'gamma · local changes', exact: true })).toBeVisible();
    await picker.getByRole('button', { name: 'beta', exact: true }).click();
    let cancelPrompt = '';
    page.once('dialog', async dialog => { cancelPrompt = dialog.message(); await dialog.dismiss(); });
    await picker.locator('summary').click();
    await picker.getByRole('button', { name: 'Close other views' }).click();
    expect(cancelPrompt).toContain('gamma');
    await expect(page.getByRole('navigation', { name: 'Open diagram views' }).locator('[data-view-id]')).toHaveCount(5);
    await expect(picker).toHaveAttribute('open', '');
    let closePrompt = '';
    page.once('dialog', async dialog => { closePrompt = dialog.message(); await dialog.accept(); });
    await picker.getByRole('button', { name: 'Close other views' }).click();
    expect(closePrompt).toContain('gamma');
    await expect(page.getByRole('navigation', { name: 'Open diagram views' }).locator('[data-view-id]')).toHaveCount(1);
    await expect(page.getByRole('navigation', { name: 'Open diagram views' }).getByRole('button', { name: 'beta', exact: true })).toHaveAttribute('aria-current', 'page');
    await expect(page.getByText(/Closed other views and discarded local changes in gamma/)).toBeVisible();
    await page.getByLabel('View ID').fill('temporary');
    await page.getByRole('button', { name: 'Choose view ID' }).click();
    await expect(page.getByRole('navigation', { name: 'Open diagram views' }).getByRole('button', { name: 'temporary', exact: true })).toHaveAttribute('aria-current', 'page');
    await picker.locator('summary').click();
    await expect(picker).toHaveAttribute('open', '');
    await picker.getByRole('button', { name: 'Close other views' }).click();
    await expect(page.getByRole('navigation', { name: 'Open diagram views' }).locator('[data-view-id]')).toHaveCount(1);
    await expect(page.getByRole('navigation', { name: 'Open diagram views' }).getByRole('button', { name: 'temporary', exact: true })).toHaveAttribute('aria-current', 'page');
    if (isMobile) await page.getByRole('navigation', { name: 'Workspace sections' }).getByRole('button', { name: 'Model' }).click();
    const activeViewKey = `chargeweave.studio.active-view.v1.${workspace.id}`;
    const beforePreview = await page.evaluate(key => localStorage.getItem(key), activeViewKey);
    await page.getByRole('button', { name: 'Preview', exact: true }).click();
    const tabs = page.getByRole('navigation', { name: 'Open diagram views' });
    await expect(tabs.getByRole('button', { name: 'Preview: Device' })).toHaveAttribute('aria-current', 'page');
    await expect(page.getByRole('button', { name: 'Save shared view' })).toBeDisabled();
    expect(await page.evaluate(key => localStorage.getItem(key), activeViewKey)).toBe(beforePreview);
    const transientPreviewId = await tabs.locator('[data-view-id^="preview-"]').getAttribute('data-view-id');
    await page.getByLabel('Filter graph relationships').fill('no matching predicate');
    if (isMobile) await page.getByRole('navigation', { name: 'Workspace sections' }).getByRole('button', { name: 'Model' }).click();
    await page.getByLabel('Search model').fill('Record');
    await page.getByRole('button', { name: 'Search', exact: true }).click();
    let replacePrompt = '';
    page.once('dialog', async dialog => { replacePrompt = dialog.message(); await dialog.dismiss(); });
    await page.getByRole('button', { name: 'Preview', exact: true }).click();
    expect(replacePrompt).toContain('discard its local view changes');
    if (isMobile) await page.getByRole('navigation', { name: 'Workspace sections' }).getByRole('button', { name: 'Diagram' }).click();
    await expect(tabs.getByRole('button', { name: 'Preview: Device, local changes' })).toHaveAttribute('aria-current', 'page');
    if (isMobile) await page.getByRole('navigation', { name: 'Workspace sections' }).getByRole('button', { name: 'Model' }).click();
    page.once('dialog', async dialog => { await dialog.accept(); });
    await page.getByRole('button', { name: 'Preview', exact: true }).click();
    await expect(tabs.getByRole('button', { name: 'Preview: Record' })).toHaveAttribute('aria-current', 'page');
    await expect(tabs.locator('[data-view-id^="preview-"]')).toHaveCount(1);
    await expect(tabs.locator('[data-view-id^="preview-"]')).toHaveAttribute('data-view-id', transientPreviewId);
    expect(await page.evaluate(key => localStorage.getItem(key), activeViewKey)).toBe(beforePreview);
    await page.getByRole('button', { name: 'Pin preview of Record' }).click();
    const pinnedPreview = tabs.locator('[data-view-id^="preview-"]');
    await expect(pinnedPreview).toHaveAttribute('aria-current', 'page');
    await expect(tabs.getByRole('button', { name: 'Pin preview of Record' })).toHaveCount(0);
    expect(await page.evaluate(key => localStorage.getItem(key), activeViewKey)).toBe(await pinnedPreview.getAttribute('data-view-id'));
    if (isMobile) await page.getByRole('navigation', { name: 'Workspace sections' }).getByRole('button', { name: 'Model' }).click();
    await page.getByRole('button', { name: 'Open in new tab', exact: true }).click();
    await expect(tabs.locator('[data-view-id^="preview-"]')).toHaveCount(2);
    const restoredTabId = await tabs.locator('[data-view-id^="preview-"][aria-current="page"]').getAttribute('data-view-id');
    await page.reload();
    if (isMobile) await page.getByRole('navigation', { name: 'Workspace sections' }).getByRole('button', { name: 'Diagram' }).click();
    const restoredTabs = page.getByRole('navigation', { name: 'Open diagram views' });
    await expect(restoredTabs.locator(`[data-view-id="${restoredTabId}"]`)).toHaveAttribute('aria-current', 'page');
    await expect(page.locator('.studio-graph > p').first()).toContainText('Record');
    expect(store.get(workspace.id).revision).toBe(0);
  } finally { await page.close(); await service.shutdown(); store.close(); }
});
